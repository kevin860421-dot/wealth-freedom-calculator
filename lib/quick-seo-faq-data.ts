/** 與 QuickSeoArticle summary 同風格，供 FAQ details 收合列使用 */
export function getQuickFaqSummaryLabel(id: number): string {
  const seoSummary = QUICK_SEO_BLOCKS[id]?.summaryLabel;
  if (seoSummary) {
    return seoSummary.replace(/^延伸閱讀/, "常見問題");
  }
  return "常見問題（點開）";
}
